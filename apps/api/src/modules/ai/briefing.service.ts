import { Injectable, Inject, Logger } from '@nestjs/common'
import { Cron, CronExpression } from '@nestjs/schedule'
import { and, eq, gte, inArray, ne, sql } from 'drizzle-orm'
import { alias } from 'drizzle-orm/pg-core'
import { tasks, taskAssignees, taskDependencies, notifications, workspaceMembers } from '@rundesk/db'
import type { Db } from '@rundesk/db'
import { DB_TOKEN } from '../../common/database/database.module'
import { AiService, type BriefingData, briefingHasContent } from './ai.service'
import { NotificationsService } from '../notifications/notifications.service'

/**
 * §7.11 — decide whether a user's daily briefing is due at `now` (UTC): they
 * must have it enabled, the current UTC hour must equal their configured hour,
 * and they must not have already been briefed on `lastSentDay` (the UTC day of
 * their most recent briefing). Pure + UTC-based so the hourly cron and the unit
 * tests agree exactly — mirrors isReportDueNow's contract.
 */
export function isBriefingDue(
  pref: { enabled: boolean; hour: number },
  lastSentDay: string | null,
  now: Date,
): boolean {
  if (!pref.enabled) return false
  const hour = Math.trunc(Number(pref.hour))
  if (!Number.isInteger(hour) || now.getUTCHours() !== hour) return false
  if (lastSentDay && lastSentDay === now.toISOString().slice(0, 10)) return false
  return true
}

/**
 * §7.11 — hourly cron that delivers per-user daily AI briefings as in-app
 * notifications. Fires only for users whose configured hour matches, once per
 * UTC day (a prior ai_briefing notification the same day suppresses a re-send).
 * The briefing body is generated by AiService (haiku when configured, else a
 * deterministic template), so it is fully testable without a live model.
 */
@Injectable()
export class BriefingService {
  private readonly logger = new Logger(BriefingService.name)

  constructor(
    @Inject(DB_TOKEN) private db: Db,
    private ai: AiService,
    private notifications: NotificationsService,
  ) {}

  @Cron(CronExpression.EVERY_HOUR, { name: 'ai-briefing-hourly' })
  async runHourly() {
    return this.dispatch(new Date())
  }

  /**
   * Select due users for `now`, skip anyone already briefed today, then
   * assemble → generate → deliver each. Returns counts so tests/ops can assert
   * selection without a live model. Best-effort per user.
   */
  async dispatch(now: Date = new Date()) {
    const recipients = await this.notifications.listBriefingRecipients()
    const due = recipients.filter((r) => isBriefingDue({ enabled: r.enabled, hour: r.hour }, null, now))
    if (due.length === 0) return { candidates: recipients.length, due: 0, sent: 0 }

    const alreadyToday = await this.usersBriefedOn(due.map((r) => r.userId), now)
    let sent = 0
    for (const r of due) {
      if (alreadyToday.has(r.userId)) continue
      try {
        const data = await this.buildBriefingData(r.userId, r.displayName ?? r.email)
        const body = await this.ai.generateBriefing(data, { userId: r.userId })
        await this.deliver(r.userId, body, data)
        sent += 1
      } catch (err) {
        this.logger.error(`Briefing failed for ${r.userId}: ${(err as Error).message}`)
      }
    }
    if (sent > 0) this.logger.log(`Delivered ${sent} daily briefing(s) for hour ${now.getUTCHours()}`)
    return { candidates: recipients.length, due: due.length, sent }
  }

  /** UserIds among `userIds` that already received an ai_briefing on `now`'s UTC day. */
  private async usersBriefedOn(userIds: string[], now: Date): Promise<Set<string>> {
    if (userIds.length === 0) return new Set()
    const dayStart = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()))
    const rows = await this.db
      .select({ userId: notifications.userId })
      .from(notifications)
      .where(
        and(
          inArray(notifications.userId, userIds),
          eq(notifications.type, 'ai_briefing'),
          gte(notifications.createdAt, dayStart),
        ),
      )
    return new Set(rows.map((r) => r.userId))
  }

  /**
   * Assemble the user's briefing buckets across every workspace they belong to:
   * overdue, due today, coming due within 3 days (at risk), and their open tasks
   * that are blocking another still-open task. Read-only reuse of the task
   * tables. Buckets are bounded so the generated prompt stays token-safe.
   */
  async buildBriefingData(userId: string, displayName: string): Promise<BriefingData> {
    const now = new Date()
    const todayStart = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()))
    const tomorrowStart = new Date(todayStart.getTime() + 86_400_000)
    const soonEnd = new Date(todayStart.getTime() + 4 * 86_400_000) // today + next 3 days

    const rows = await this.db
      .select({ title: tasks.title, dueDate: tasks.dueDate })
      .from(taskAssignees)
      .innerJoin(tasks, eq(tasks.id, taskAssignees.taskId))
      .where(and(eq(taskAssignees.userId, userId), eq(tasks.isArchived, false), ne(tasks.statusCategory, 'closed')))

    const overdue: string[] = []
    const dueToday: string[] = []
    const atRisk: string[] = []
    for (const t of rows) {
      if (!t.dueDate) continue
      const due = new Date(t.dueDate)
      if (due < todayStart) overdue.push(t.title)
      else if (due < tomorrowStart) dueToday.push(t.title)
      else if (due < soonEnd) atRisk.push(t.title)
    }

    return {
      displayName,
      overdue: overdue.slice(0, 20),
      dueToday: dueToday.slice(0, 20),
      atRisk: atRisk.slice(0, 20),
      blocking: await this.blockingTasks(userId),
    }
  }

  /** Distinct titles of the user's open tasks that block another still-open task. */
  private async blockingTasks(userId: string): Promise<string[]> {
    const blocker = alias(tasks, 'blocker')
    const blocked = alias(tasks, 'blocked')
    const rows = await this.db
      .select({ title: blocker.title })
      .from(taskDependencies)
      .innerJoin(
        blocker,
        sql`${blocker.id} = case when ${taskDependencies.type} = 'blocks' then ${taskDependencies.taskId} else ${taskDependencies.relatedTaskId} end`,
      )
      .innerJoin(
        blocked,
        sql`${blocked.id} = case when ${taskDependencies.type} = 'blocks' then ${taskDependencies.relatedTaskId} else ${taskDependencies.taskId} end`,
      )
      .innerJoin(taskAssignees, and(eq(taskAssignees.taskId, blocker.id), eq(taskAssignees.userId, userId)))
      .where(
        and(
          inArray(taskDependencies.type, ['blocks', 'blocked_by']),
          ne(blocker.statusCategory, 'closed'),
          eq(blocker.isArchived, false),
          ne(blocked.statusCategory, 'closed'),
          eq(blocked.isArchived, false),
        ),
      )
    const titles = [...new Set(rows.map((r) => r.title))]
    return titles.slice(0, 20)
  }

  /**
   * Deliver the briefing as an in-app `ai_briefing` notification (the simplest
   * reliable path — respects the user's activity-channel prefs). Associates it
   * with the user's first workspace so it deep-links to that insights page.
   */
  private async deliver(userId: string, body: string, data: BriefingData): Promise<void> {
    const [membership] = await this.db
      .select({ workspaceId: workspaceMembers.workspaceId })
      .from(workspaceMembers)
      .where(eq(workspaceMembers.userId, userId))
      .limit(1)
    const workspaceId = membership?.workspaceId ?? null
    const counts =
      data.overdue.length + data.dueToday.length + data.blocking.length + data.atRisk.length
    await this.notifications.create({
      userId,
      workspaceId,
      type: 'ai_briefing',
      title: briefingHasContent(data) ? `Your daily briefing (${counts})` : 'Your daily briefing',
      body,
      target: workspaceId
        ? { entityType: 'insights', entityId: workspaceId, url: `/app/${workspaceId}/insights` }
        : undefined,
    })
  }
}
