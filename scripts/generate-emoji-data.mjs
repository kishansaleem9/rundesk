#!/usr/bin/env node
/**
 * Regenerate `apps/web/src/lib/emoji-data.ts` from the Unicode emoji list.
 *
 * §2.8 gap 7 — "poori ki poori emoji icons ki list". A hand-typed emoji list is
 * a list somebody will have to keep typing; the authoritative one is published
 * by Unicode and repackaged as `unicode-emoji-json` (MIT, data under the
 * Unicode licence). We take the tarball, generate a plain data module, and
 * commit that — so the app ships no new dependency and does no network call to
 * show a picker.
 *
 * Run:  node scripts/generate-emoji-data.mjs
 *
 * The tarball is fetched from the npm registry into a temp dir and thrown away
 * afterwards. Re-run it when Unicode publishes a new emoji version; the diff
 * on the generated file is the new emoji.
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const PACKAGE = 'unicode-emoji-json'
const VERSION = '0.9.0'
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'apps/web/src/lib/emoji-data.ts')

/**
 * The picker's tabs, in the order the client's reference showed them — note
 * that it merges Unicode's two people groups into one "Smiles & People" tab,
 * and that Activities comes before Travel, which is not Unicode's order.
 */
const CATEGORIES = [
  { id: 'people', groups: ['Smileys & Emotion', 'People & Body'] },
  { id: 'nature', groups: ['Animals & Nature'] },
  { id: 'food', groups: ['Food & Drink'] },
  { id: 'activity', groups: ['Activities'] },
  { id: 'travel', groups: ['Travel & Places'] },
  { id: 'objects', groups: ['Objects'] },
  { id: 'symbols', groups: ['Symbols'] },
  { id: 'flags', groups: ['Flags'] },
]

const ZWJ = '\u200d'

/**
 * Can a skin tone be applied to this emoji without inventing a sequence no
 * font has?
 *
 * A tone modifier goes after the person it colours. That is unambiguous for
 * a lone person (👍 → 👍🏽) and for a person joined to an object (🧑‍💻 → 🧑🏽‍💻),
 * but a couple carries two people (👩‍❤️‍👨) and toning only the first would be
 * a sequence outside the recommended set — it renders as loose emoji side by
 * side. Those seven are offered untoned rather than offered broken.
 */
function toneIsSafe(emoji) {
  if (!emoji.includes(ZWJ)) return true
  const people = [...emoji].filter((c) => {
    const cp = c.codePointAt(0)
    return (cp >= 0x1f466 && cp <= 0x1f469) || cp === 0x1f9d1 || cp === 0x1f9d4 || cp === 0x1f471
  })
  return people.length <= 1
}

const dir = mkdtempSync(join(tmpdir(), 'emoji-'))
try {
  const url = `https://registry.npmjs.org/${PACKAGE}/-/${PACKAGE}-${VERSION}.tgz`
  execFileSync('curl', ['-sSfL', '--max-time', '120', '-o', join(dir, 'p.tgz'), url])
  execFileSync('tar', ['xzf', join(dir, 'p.tgz'), '-C', dir])
  const byGroup = JSON.parse(readFileSync(join(dir, 'package/data-by-group.json'), 'utf8'))
  const groups = new Map(byGroup.map((g) => [g.name, g.emojis]))

  let total = 0
  const blocks = CATEGORIES.map((cat) => {
    const rows = []
    for (const name of cat.groups) {
      const list = groups.get(name)
      if (!list) throw new Error(`Unicode group "${name}" is not in the data — the category map is stale`)
      for (const e of list) {
        // "|" separates the fields and "\n" the entries, so neither may appear
        // in a name. Unicode names are ASCII words, but assert rather than
        // silently emit a file that parses into nonsense.
        if (e.name.includes('|') || e.name.includes('\n')) throw new Error(`unusable name: ${e.name}`)
        const tone = e.skin_tone_support && toneIsSafe(e.emoji) ? '|1' : ''
        rows.push(`${e.emoji}|${e.name}${tone}`)
        total++
      }
    }
    return `  ${cat.id}: \`${rows.join('\\n')}\`,`
  })

  const header = `// GENERATED by scripts/generate-emoji-data.mjs — do not edit by hand.
// Source: ${PACKAGE}@${VERSION} (MIT), repackaging the Unicode emoji list.
//
// Held as one string per category rather than ${total} object literals: the
// same data at a fraction of the bytes, parsed once on first open. Each line is
// "<emoji>|<name>" with a trailing "|1" when a skin tone can be applied.
`
  writeFileSync(OUT, `${header}export const EMOJI_BY_CATEGORY: Record<string, string> = {\n${blocks.join('\n')}\n}\n`)
  console.log(`wrote ${OUT} — ${total} emoji across ${CATEGORIES.length} categories`)
} finally {
  rmSync(dir, { recursive: true, force: true })
}
